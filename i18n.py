def normalize_language(value) -> str:
    parts = str(value or "").replace("-", "_").lower().split("_")
    code = parts[0]
    if code == "zh" and any(part in {"hant", "tw", "hk", "mo"} for part in parts[1:]):
        return "zh_Hant"
    return code if code in LANGUAGE_NAMES else "en"


def translate(language: str, key: str, **params) -> str:
    return TEXT[normalize_language(language)][key].format(**params)
